def build_colors_css() -> str:
    """Render a gtk colors.css: rb_ tokens + libadwaita contract."""
    lines = [f"/* {HEADER_COMMENT} */"]
    for theme_name, rb_name in CORE_TOKENS:
        lines.append(f"@define-color {rb_name} {theme_tokens.css(theme_name)};")
    lines.append("")
    lines.append("/* libadwaita named-color contract (references the rb_ tokens). */")
    for lib_name, rb_name in LIBADWAITA:
        lines.append(f"@define-color {lib_name} @{rb_name};")
    return "\n".join(lines) + "\n"


def _aarrggbb(value: str) -> str:
    """Normalize a token/literal hex to lowercase #aarrggbb (opaque: ff...)."""
    text = value.strip()
    if not text.startswith("#"):
        raise ValueError(f"Not a hex color: {value!r}")
    digits = text[1:]
    if len(digits) == 6:
        return "#ff" + digits.lower()
    if len(digits) == 8:
        return "#" + digits.lower()
    raise ValueError(f"Unsupported hex color: {value!r}")


def _palette_value(spec: str) -> str:
    if spec.startswith("#"):
        return _aarrggbb(spec)
    value = theme_tokens.tokens()[spec]
    if isinstance(value, int):
        raise TypeError(f"Token {spec!r} is an int, not a color")
    return _aarrggbb(value)


def build_rich_black_conf() -> str:
    """Render qt6ct/colors/rich-black.conf ([ColorScheme] palette)."""
    lines = [
        f"# {HEADER_COMMENT}",
        "[ColorScheme]",
        "# Role order: " + ", ".join(ROLES) + ".",
    ]
    for label, table in (
        ("active", ACTIVE_MAP),
        ("disabled", DISABLED_MAP),
        ("inactive", INACTIVE_MAP),
    ):
        values = ", ".join(_palette_value(table[role]) for role in ROLES)
        lines.append(f"{label}_colors={values}")
    return "\n".join(lines) + "\n"


def build_qss() -> str:
    """Render qt6ct/qss/rich-black.qss from the template.

    Every ``{{name}}`` placeholder is substituted: color tokens via
    ``theme_tokens.qss(name)``, radius/int tokens via their integer
    value. Unknown placeholders are a hard error.
    """
    template = TEMPLATE.read_text(encoding="utf-8")
    data = theme_tokens.tokens()

    def replace(match: re.Match) -> str:
        name = match.group(1)
        if name not in data:
            raise ValueError(
                f"Unknown placeholder '{{{{{name}}}}}' in {TEMPLATE}; "
                "it matches no Theme.qml color or int token."
            )
        value = data[name]
        if isinstance(value, int):
            return str(value)
        return theme_tokens.qss(name)

    rendered = PLACEHOLDER_RE.sub(replace, template)
    if not rendered.endswith("\n"):
        rendered += "\n"
    return f"/* {HEADER_COMMENT} */\n" + rendered


def build_all() -> dict[Path, str]:
    """Render every generated file; return {absolute path: content}."""
    colors_css = build_colors_css()
    return {
        CONFIG_ROOT / "gtk-3.0" / "colors.css": colors_css,
        CONFIG_ROOT / "gtk-4.0" / "colors.css": colors_css,
        CONFIG_ROOT / "qt6ct" / "colors" / "rich-black.conf": (
            build_rich_black_conf()
        ),
        CONFIG_ROOT / "qt6ct" / "qss" / "rich-black.qss": build_qss(),
    }


def cmd_render() -> int:
    planned = build_all()
    for path, content in planned.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    return 0


def cmd_check() -> int:
    errors: list[str] = []

    planned = build_all()
    for path, content in planned.items():
        if not path.exists():
            errors.append(f"missing generated file: {path} (run 'render')")
        elif path.read_text(encoding="utf-8") != content:
            errors.append(f"drift detected: {path} differs; run 'render'")

    # Rule (d): palette role order/count guard. The qt6ct [ColorScheme]
    # contract maps list index i -> QPalette::ColorRole(i), so ROLES must
    # match the Qt >= 6.6 enum exactly (including the NoRole slot) and
    # the golden roles around it must keep their token bindings.
    if ROLES != EXPECTED_ROLES:
        errors.append(
            "palette ROLES drifted from the Qt>=6.6 QPalette::ColorRole "
            f"order: {ROLES!r} != {EXPECTED_ROLES!r}"
        )
    if len(ROLES) != QT66_NCOLORROLES:
        errors.append(
            f"palette role count {len(ROLES)} != QPalette::NColorRoles "
            f"({QT66_NCOLORROLES}) for Qt>=6.6; the NoRole slot may be missing"
        )
    for role, token in PALETTE_GOLDEN.items():
        if ACTIVE_MAP.get(role) != token:
            errors.append(
                f"palette ACTIVE_MAP[{role!r}] is {ACTIVE_MAP.get(role)!r}, "
                f"expected token {token!r}"
            )
    conf_text = planned[CONFIG_ROOT / "qt6ct" / "colors" / "rich-black.conf"]
    active_line = next(
        (
            line
            for line in conf_text.splitlines()
            if line.startswith("active_colors=")
        ),
        "",
    )
    active_values = active_line.partition("=")[2].split(", ")
    for role in ("NoRole", "ToolTipBase", "ToolTipText", "PlaceholderText",
                 "Accent"):
        try:
            index = ROLES.index(role)
        except ValueError:
            errors.append(f"palette ROLES missing role {role!r}")
            continue
        expected = _palette_value(ACTIVE_MAP[role])
        got = active_values[index] if index < len(active_values) else "<short>"
        if got != expected:
            errors.append(
                f"palette active_colors[{index}] ({role}) is {got}, "
                f"expected {expected}; role order is shifted"
            )

    for css_path in (
        CONFIG_ROOT / "gtk-3.0" / "gtk.css",
        CONFIG_ROOT / "gtk-4.0" / "gtk.css",
    ):
        if not css_path.exists():
            print(f"note: {css_path} absent, skipping raw-color rule")
            continue
        text = css_path.read_text(encoding="utf-8")
        probe_text = CSS_COMMENT_RE.sub("", text)
        hex_hit = RAW_HEX_RE.search(probe_text)
        rgba_hit = RGBA_RE.search(probe_text)
        func_hit = RAW_FUNC_RE.search(probe_text)
        named_hit = CSS_NAMED_COLOR_RE.search(probe_text)
        if hex_hit:
            errors.append(
                f"{css_path} contains raw hex color {hex_hit.group(0)!r}; "
                "use @rb_* / libadwaita @-names only"
            )
        if rgba_hit:
            errors.append(
                f"{css_path} contains an rgba() literal; "
                "use @rb_* / libadwaita @-names only"
            )
        if func_hit:
            errors.append(
                f"{css_path} contains a raw color function "
                f"{func_hit.group(0)!r}; use @rb_* / libadwaita @-names only"
            )
        if named_hit:
            errors.append(
                f"{css_path} contains a CSS named color "
                f"{named_hit.group(0)!r}; use @rb_* / libadwaita @-names only"
            )

    # Rule (c): every @NAME referenced in gtk.css must be defined by the
    # sibling colors.css @define-color set or by a @define-color in the
    # gtk.css file itself (locally-defined names are valid).
    for css_path in (
        CONFIG_ROOT / "gtk-3.0" / "gtk.css",
        CONFIG_ROOT / "gtk-4.0" / "gtk.css",
    ):
        if not css_path.exists():
            print(f"note: {css_path} absent, skipping token-reference rule")
            continue
        colors_path = css_path.parent / "colors.css"
        if not colors_path.exists():
            errors.append(
                f"{css_path} has no sibling {colors_path}; "
                "cannot resolve @-name references"
            )
            continue
        css_text = css_path.read_text(encoding="utf-8")
        defined = set(
            DEFINE_COLOR_RE.findall(
                colors_path.read_text(encoding="utf-8")
            )
        ) | set(DEFINE_COLOR_RE.findall(css_text))
        referenced: set[str] = set()
        for line in css_path.read_text(encoding="utf-8").splitlines():
            # The name being defined on its own @define-color line is a
            # definition, not a reference.
            probe = DEFINE_COLOR_RE.sub("", line)
            for match in AT_REF_RE.finditer(probe):
                name = match.group(1)
                if name in AT_RULE_EXCLUDE:
                    continue
                if name.startswith("-"):
                    # @-gtk-...-style vendor at-rules.
                    continue
                referenced.add(name)
        undefined = sorted(referenced - defined)
        if undefined:
            errors.append(
                f"{css_path} references undefined color(s): "
                + ", ".join(f"@{name}" for name in undefined)
                + f" (not defined in {colors_path})"
            )

    if errors:
        for message in errors:
            print(f"FAIL: {message}", file=sys.stderr)
        return 1
    print(
        f"OK: {len(planned)} generated files match Theme.qml; "
        "gtk.css raw-color rule holds; gtk.css token references resolve."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate Rich Black theme files from Theme.qml."
    )
    parser.add_argument(
        "command",
        nargs="?",
        choices=("render", "check"),
        default="render",
        help="render generated files (default) or check them for drift",
    )
    args = parser.parse_args(argv)
    try:
        if args.command == "check":
            return cmd_check()
        return cmd_render()
    except (ValueError, KeyError, TypeError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
