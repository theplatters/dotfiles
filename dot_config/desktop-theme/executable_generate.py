#!/usr/bin/env python3
"""Regenerate Rich Black desktop-theme outputs from Theme.qml.

Subcommands:
  render (default)  Regenerate all generated files deterministically.
  check             (a) Fail if on-disk generated files drift from what a
                    fresh render would produce; (b) fail if the
                    hand-authored gtk-3.0/gtk.css / gtk-4.0/gtk.css files
                    contain raw colors (hex literals, raw color functions
                    such as rgb()/rgba()/hsl()/hsla()/hwb()/lab()/lch()/
                    oklab()/oklch()/color-mix()/alpha()/shade()/mix()/
                    lighter()/darker(), or CSS named colors -- they must
                    use only @rb_* / libadwaita @-names); (c) fail if any
                    @NAME referenced in gtk-3.0/gtk.css / gtk-4.0/gtk.css
                    is not defined by the sibling colors.css
                    @define-color set or by a @define-color in the gtk.css
                    file itself; (d) fail if the qt6ct palette ROLES list
                    drifts from the Qt>=6.6 QPalette::ColorRole order
                    (including the NoRole slot) or the golden ToolTipBase /
                    ToolTipText / PlaceholderText / Accent bindings break.
                    Missing gtk.css files are skipped with a note.

All generated files carry a "generated by ... -- do not edit" header.
Rendering is idempotent: stable ordering, no timestamps.
"""

